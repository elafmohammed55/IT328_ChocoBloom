    private static final String PLACEHOLDER_IMAGE = "/images/placeholder.png";

    private Product product;
    private int stock;
    private CartData cart;

    public ProductItemPanel() {
        initComponents();
        showImage(null);
    }

    /** Fill the row with one product from the team's Product class. */
    public void setProduct(Product product) {
        this.product = product;
        nameLabel.setText(product.getName());
        descriptionLabel.setText(product.getDescription());
        priceLabel.setText(String.format("Price: %.2f", product.getPrice()));
        showImage(product.getImagePath());
        setStock(product.getStock());
    }

    /** The cart that the Add button adds to. */
    public void setCart(CartData cart) {
        this.cart = cart;
    }

    /** Show a new stock value (called when the team code sends updated stock). */
    public void setStock(int newStock) {
        this.stock = newStock;
        stockLabel.setText("Stock: " + newStock);
        quantityComboBox.removeAllItems();
        for (int i = 1; i <= newStock; i++) {
            quantityComboBox.addItem(String.valueOf(i));
        }
    }

    public Product getProduct() {
        return product;
    }

    /** imagePath example: "/images/milk_chocolate.png" (inside src/main/resources). */
    private void showImage(String imagePath) {
        URL url = null;
        if (imagePath != null && !imagePath.isEmpty()) {
            url = getClass().getResource(imagePath);
        }
        if (url == null) {
            url = getClass().getResource(PLACEHOLDER_IMAGE);
        }
        if (url != null) {
            Image img = new ImageIcon(url).getImage().getScaledInstance(80, 80, Image.SCALE_SMOOTH);
            imageLabel.setIcon(new ImageIcon(img));
        }
    }

